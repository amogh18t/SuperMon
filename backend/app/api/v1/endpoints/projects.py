@router.post("/{project_id}/decompose")
async def decompose_project_stories(
    project_id: int,
    db: Session = Depends(get_db),
    agent_manager: AgentManager = Depends(get_agent_manager),
):
    """AI Decompose: generates new Epics and User Stories using Planning Agent."""
    project = db.query(Project).filter(Project.id == project_id).first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    target_epic = project.epics[0] if project.epics else None
    if not target_epic:
        target_epic = Epic(
            project_id=project.id,
            name="AI Orchestrated Epic",
            description="Generated by Planning Agent decomposition.",
            status=EpicStatus.IN_PROGRESS,
        )
        db.add(target_epic)
        db.flush()

    story_titles = [
        "AI-Synthesized Telemetry Circuit Breaker & Slack Alerting",
        "Autonomous Cache Invalidation via Redis Pub/Sub",
        "Dynamic Model Context Token Balancer Hook",
        "Automated GitHub Milestone Synchronizer",
    ]
    picked_title = random.choice(story_titles)

    new_story = UserStory(
        epic_id=target_epic.id,
        title=picked_title,
        description="Automatically generated by Requirements & Planning Agents based on repository analysis.",
        status=UserStoryStatus.TODO,
        priority=Priority.HIGH,
        story_points=random.choice([3, 5, 8]),
        acceptance_criteria={
            "items": ["Zero-downtime fallback", "Automated pytest suite passes"]
        },
    )
    db.add(new_story)
    db.commit()
    db.refresh(project)

    return {
        "success": True,
        "message": f"Generated story '{picked_title}'",
        "project": _format_project_hierarchy(project),
    }


@router.get("/", response_model=List[ProjectResponse])
async def get_projects(
    status_filter: Optional[ProjectStatus] = None,
    priority_filter: Optional[Priority] = None,
    db: Session = Depends(get_db),
):
    """Get all projects with optional filtering"""
    query = db.query(Project)
    if status_filter:
        query = query.filter(Project.status == status_filter)
    if priority_filter:
        query = query.filter(Project.priority == priority_filter)
    projects = query.all()
    return [ProjectResponse.from_orm(project) for project in projects]


@router.get("/{project_id}/status")
async def get_project_status(project_id: int, db: Session = Depends(get_db)):
    """Get detailed project status and metrics"""
    project = db.query(Project).filter(Project.id == project_id).first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    total_epics = len(project.epics)
    completed_epics = len(
        [
            epic
            for epic in project.epics
            if getattr(epic.status, "value", str(epic.status)) == "done"
        ]
    )
    total_stories = sum(len(epic.user_stories) for epic in project.epics)
    completed_stories = sum(
        len(
            [
                story
                for story in epic.user_stories
                if getattr(story.status, "value", str(story.status)) == "done"
            ]
        )
        for epic in project.epics
    )
    progress_percentage = (
        (completed_stories / total_stories * 100) if total_stories > 0 else 0
    )

    return {
        "project_id": project_id,
        "name": project.name,
        "status": getattr(project.status, "value", str(project.status)),
        "progress_percentage": round(progress_percentage, 2),
        "total_epics": total_epics,
        "completed_epics": completed_epics,
        "total_stories": total_stories,
        "completed_stories": completed_stories,
        "start_date": project.start_date.isoformat() if project.start_date else None,
        "updated_at": project.updated_at.isoformat() if project.updated_at else None,
    }


