def _format_project_hierarchy(project: Project) -> Dict[str, Any]:
    """Helper to convert Project ORM into frontend hierarchy shape."""
    epics_list = []
    total_stories = 0
    done_stories = 0

    for epic in project.epics:
        stories_list = []
        for story in epic.user_stories:
            total_stories += 1
            st_val = (
                story.status.value
                if hasattr(story.status, "value")
                else str(story.status)
            )
            if st_val == "done":
                done_stories += 1

            # Map status to frontend Kanban status
            frontend_status = (
                "Done"
                if st_val == "done"
                else (
                    "In Progress"
                    if st_val == "in_progress"
                    else ("Testing" if st_val == "review" else "Ready")
                )
            )

            pri_val = (
                story.priority.value
                if hasattr(story.priority, "value")
                else str(story.priority)
            )
            ac = story.acceptance_criteria
            ac_items = (
                ac.get("items", [])
                if isinstance(ac, dict)
                else (ac if isinstance(ac, list) else ["Verified by Testing Agent"])
            )

            stories_list.append(
                {
                    "id": f"US-{story.id}",
                    "epic_id": f"epic-{epic.id}",
                    "title": story.title,
                    "description": story.description
                    or "Autonomous user story generated by Planning Agent.",
                    "acceptance_criteria": ac_items
                    or ["Automated testing suite passes"],
                    "story_points": story.story_points or 5,
                    "priority": pri_val.capitalize() if pri_val else "High",
                    "status": frontend_status,
                    "assigned_agent": "Development Agent"
                    if frontend_status in ("In Progress", "Ready")
                    else (
                        "Testing Agent"
                        if frontend_status == "Testing"
                        else "Requirements Agent"
                    ),
                }
            )

        epic_done = len([s for s in stories_list if s["status"] == "Done"])
        epic_prog = round(epic_done / len(stories_list) * 100) if stories_list else 0

        epics_list.append(
            {
                "id": f"epic-{epic.id}",
                "project_id": f"proj-{project.id}",
                "title": epic.name,
                "description": epic.description
                or "Epic managed by Multi-Agent Orchestration.",
                "status": "In Progress"
                if epic.status.value == "in_progress"
                else "Planning",
                "progress": epic_prog,
                "stories": stories_list,
            }
        )

    proj_prog = round(done_stories / total_stories * 100) if total_stories > 0 else 25

    return {
        "id": f"proj-{project.id}",
        "raw_id": project.id,
        "name": project.name,
        "description": project.description
        or "Autonomous multi-agent software engineering initiative.",
        "status": "Active"
        if project.status.value in ("planning", "in_progress")
        else "Completed",
        "progress": proj_prog,
        "github_repo": project.github_repo_url or "amogh18t/supermon",
        "updated_at": "Just now",
        "epics": epics_list,
    }


@router.post("/", response_model=ProjectResponse, status_code=status.HTTP_201_CREATED)
async def create_project(
    project_data: ProjectCreate,
    db: Session = Depends(get_db),
    agent_manager: AgentManager = Depends(get_agent_manager),
):
    """Create a new project and seed initial scaffolding."""
    try:
        project = Project(
            name=project_data.name,
            description=project_data.description,
            status=ProjectStatus.PLANNING,
            priority=project_data.priority,
            start_date=datetime.utcnow(),
            budget=project_data.budget,
            team_size=project_data.team_size,
        )
        db.add(project)
        db.flush()

        # Automatically seed an initial Epic and User Story
        initial_epic = Epic(
            project_id=project.id,
            name="Core Architecture & MVP Scaffolding",
            description="Initial Epic generated by Requirements Agent.",
            status=EpicStatus.IN_PROGRESS,
            priority=project_data.priority,
            estimated_hours=40,
        )
        db.add(initial_epic)
        db.flush()

        initial_story = UserStory(
            epic_id=initial_epic.id,
            title="Initialize Repository, FastAPI Skeleton & CI Pipeline",
            description="Bootstrap service with pre-commit hooks and pytest.",
            status=UserStoryStatus.TODO,
            priority=Priority.CRITICAL,
            story_points=5,
            acceptance_criteria={"items": ["GitHub repo synced", "CI green"]},
        )
        db.add(initial_story)

        db.commit()
        db.refresh(project)
        return ProjectResponse.from_orm(project)

    except Exception as e:
        db.rollback()
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to create project: {str(e)}",
        )


@router.get("/status")
async def get_all_projects_status(db: Session = Depends(get_db)):
    """Get aggregated metrics across all projects for dashboard stats."""
    projects = db.query(Project).all()
    total_epics = sum(len(p.epics) for p in projects)
    all_stories = [s for p in projects for e in p.epics for s in e.user_stories]
    total_stories = len(all_stories)
    done_stories = len(
        [s for s in all_stories if getattr(s.status, "value", str(s.status)) == "done"]
    )

    return {
        "total_projects": len(projects),
        "total_epics": total_epics,
        "total_stories": total_stories,
        "done_stories": done_stories,
        "completion_rate": round(done_stories / total_stories * 100, 1)
        if total_stories > 0
        else 0,
    }


